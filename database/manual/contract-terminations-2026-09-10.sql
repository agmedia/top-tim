  UNIQUE KEY `contract_terminations_reference_unique` (`reference`),
  KEY `contract_terminations_status_submitted_at_index` (`status`,`submitted_at`),
  KEY `contract_terminations_user_id_index` (`user_id`),
  KEY `contract_terminations_order_id_index` (`order_id`),
  KEY `contract_terminations_order_number_index` (`order_number`),
  KEY `contract_terminations_email_index` (`email`),
  KEY `contract_terminations_status_index` (`status`),
  KEY `contract_terminations_submitted_at_index` (`submitted_at`),
  KEY `contract_terminations_handled_by_index` (`handled_by`)
